/**
 * Returns translated UI string
 */
export const getUiText = (key, lang = 'en') => {
  const dict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
  return dict[key] || UI_TRANSLATIONS.en[key] || key;
};

/**
 * Resolves localized survey fields (title, description, welcomeMessage, endMessage)
 */
export const getLocalizedSurvey = (survey, lang = 'en') => {
  if (!survey) return survey;
  if (!lang || lang === 'en') return survey;

  const surveySettings = survey.settings || {};
  const trans = surveySettings.translations?.[lang] || {};

  return {
    ...survey,
    title: trans.title?.trim() || survey.title,
    description: trans.description !== undefined ? trans.description : survey.description,
    welcomeMessage: trans.welcomeMessage !== undefined ? trans.welcomeMessage : survey.welcomeMessage,
    endMessage: trans.endMessage !== undefined ? trans.endMessage : survey.endMessage,
  };
};

/**
 * Resolves localized question fields (text, helpText, options, rows, columns)
 */
export const getLocalizedQuestion = (question, lang = 'en', surveySettings = null) => {
  if (!question) return question;
  if (!lang || lang === 'en') return question;

  const qSettings = question.settings || {};
  // Translation can be stored directly in question.settings.translations[lang]
  // or centrally in surveySettings.translations[lang].questions[q.code]
  const qTrans =
    qSettings.translations?.[lang] ||
    surveySettings?.translations?.[lang]?.questions?.[question.code] ||
    surveySettings?.translations?.[lang]?.questions?.[String(question.id)] ||
    {};

  const localizedText = qTrans.text?.trim() || question.text;
  const localizedHelp = qTrans.helpText !== undefined ? qTrans.helpText : question.helpText;

  // Localize Answer Options
  const localizedOptions = (question.options || []).map((opt) => {
    const optTrans = qTrans.options?.[opt.code];
    return {
      ...opt,
      text: typeof optTrans === 'string' && optTrans.trim() ? optTrans.trim() : opt.text,
    };
  });

  // Localize Matrix Rows & Columns if applicable
  let localizedSettings = { ...qSettings };
  if (question.type === 'matrix') {
    const rows = qTrans.rows || qSettings.rows;
    const columns = qTrans.columns || qSettings.columns;
    localizedSettings = {
      ...localizedSettings,
      rows: Array.isArray(rows) ? rows : qSettings.rows,
      columns: Array.isArray(columns) ? columns : qSettings.columns,
    };
  }

  return {
    ...question,
    text: localizedText,
    helpText: localizedHelp,
    options: localizedOptions,
    settings: localizedSettings,
  };
};
